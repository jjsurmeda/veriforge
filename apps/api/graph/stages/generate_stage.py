"""Generate stage: the run's answer, streamed token by token.

Which generator runs is the run's shape, not a parameter: a direct small-talk
or library reply, the abstention template, or the grounded answer with its
citations.
"""

from __future__ import annotations

from collections.abc import AsyncIterator
from typing import TYPE_CHECKING

from graph.abstain import stream_abstention

if TYPE_CHECKING:
    from graph.stages.state import AutoRun


async def _stream_abstention(run: AutoRun) -> AsyncIterator[str]:
    if run.abstain_event is None:
        return
    async for token in stream_abstention(
        run.abstain_event,
        litellm_model=run.params.litellm_model,
        question=run.rewritten,
        metadata={
            "run_id": str(run.params.run_id),
            "user_id": str(run.params.user_id),
        },
    ):
        yield token


async def stream_answer(run: AutoRun) -> AsyncIterator[str]:
    metadata = {
        "run_id": str(run.params.run_id),
        "user_id": str(run.params.user_id),
    }
    if run.chitchat:
        async for token in run.seams.stream_chitchat_reply(
            litellm_model=run.params.litellm_model,
            message=run.rewritten,
            history=run.history,
            metadata=metadata,
        ):
            yield token
        return
    if run.library_names is not None:
        async for token in run.seams.stream_library_reply(
            litellm_model=run.params.litellm_model,
            question=run.rewritten,
            names=run.library_names,
            history=run.history,
            metadata=metadata,
        ):
            yield token
        return
    if run.abstain_event is not None:
        # Abstention path: the fixed-template output is generated by the same
        # streaming generator with a directive prompt — the LLM only renders
        # the template, not free-form text (TR-4).
        async for token in _stream_abstention(run):
            yield token
        return
    async for token in run.seams.stream_grounded_answer(
        litellm_model=run.params.litellm_model,
        question=run.rewritten,
        contexts=run.contexts,
        history=run.history,
        metadata=metadata,
        # The intent ingress already decided (TRD §7), used to pick the
        # generator's per-intent block. No extra call: it is a value the run
        # is already carrying.
        intent=run.ingress.intent,
    ):
        yield token
